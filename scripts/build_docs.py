def run(folder, check):
    data, cats, errs = load(folder)
    loose = unregistered(folder, data)
    errs += [f'not in docs.json: {folder.name}/{p}  (add it to "docs", or to "ignore" with a reason)' for p in loose]
    if errs:
        return errs
    outputs = {folder / 'index.html': build_index(folder, data, cats),
               folder / 'docs.html': build_docs_page(folder, data, cats)}
    problems = []
    for path, text in outputs.items():
        current = path.read_text(encoding='utf-8') if path.exists() else ''
        if current != text:
            if check:
                problems.append(f'out of date: {path.relative_to(ROOT)}  (run: python3 scripts/build_docs.py {folder.name})')
            else:
                path.write_text(text, encoding='utf-8')
                print(f'wrote {path.relative_to(ROOT)}')
    if not check and not problems:
        print(f'{folder.name}: {len(data["docs"])} docs, {sum(d["status"] == "wip" for d in data["docs"])} wip')
    return problems


def main(argv):
    check = '--check' in argv
    names = [a for a in argv if not a.startswith('--')]
    folders = [p.parent for p in sorted(ROOT.glob('*/docs.json'))] if '--all' in argv else [ROOT / n for n in names]
    if not folders:
        print(__doc__)
        return 2
    problems = []
    for f in folders:
        problems += run(f, check)
    for p in problems:
        print('✗ ' + p, file=sys.stderr)
    if check and not problems:
        print('doc center OK: ' + ', '.join(f.name for f in folders))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
